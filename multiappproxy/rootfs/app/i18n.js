  if (!CATALOGUE[lang]) { lang = 'en'; }

  window.MAP_LANG = lang;

  /* Look up a key, English being the fallback for anything a translation misses,
     and the key itself the last resort so a gap shows up rather than blanking. */
  window.mapT = function (key, params) {
    var text = CATALOGUE[lang][key];
    if (text === undefined) { text = CATALOGUE.en[key]; }
    if (text === undefined) { return key; }
    if (params) {
      Object.keys(params).forEach(function (name) {
        text = text.split('{' + name + '}').join(String(params[name]));
      });
    }
    return text;
  };

  /* The analyzer mixes both: {id, params} for anything it wrote, and a plain
     string for what must not be translated, an option name for instance. */
  window.mapMsg = function (message) {
    if (message === null || message === undefined) { return ''; }
    if (typeof message === 'string') { return message; }
    return window.mapT(message.id, message.params);
  };
